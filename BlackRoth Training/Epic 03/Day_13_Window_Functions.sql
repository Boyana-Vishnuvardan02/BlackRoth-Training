#How much did sales change from the previous month?
WITH MONTHLY_REVENUE AS (
SELECT DATE_FORMAT(O.ORDER_DATE, '%Y-%m') AS SALES_MONTH,SUM(OI.QUANTITY * OI.UNIT_PRICE) AS REVENUE
FROM ORDERS O
JOIN ORDER_ITEMS OI
ON O.ORDER_ID = OI.ORDER_ID
GROUP BY DATE_FORMAT(O.ORDER_DATE, '%Y-%m')),
MONTHLY_COMPARISON AS (
SELECT SALES_MONTH,REVENUE,
LAG(REVENUE) OVER(
ORDER BY SALES_MONTH) AS PREVIOUS_REVENUE
FROM MONTHLY_REVENUE)
SELECT SALES_MONTH,REVENUE,PREVIOUS_REVENUE,REVENUE - PREVIOUS_REVENUE AS REVENUE_CHANGE,ROUND((REVENUE - PREVIOUS_REVENUE)/ NULLIF(PREVIOUS_REVENUE, 0)* 100,2) AS MOM_PERCENT_CHANGE
FROM MONTHLY_COMPARISON
ORDER BY SALES_MONTH;

#What is the cumulative revenue?
WITH MONTHLY_REVENUE AS (
SELECT DATE_FORMAT(O.ORDER_DATE, '%Y-%m') AS SALES_MONTH,SUM(OI.QUANTITY * OI.UNIT_PRICE) AS REVENUE
FROM ORDERS O
JOIN ORDER_ITEMS OI
ON O.ORDER_ID = OI.ORDER_ID
GROUP BY DATE_FORMAT(O.ORDER_DATE, '%Y-%m'))
SELECT SALES_MONTH,REVENUE,
SUM(REVENUE) OVER(
ORDER BY SALES_MONTH
ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS CUMULATIVE_REVENUE
FROM MONTHLY_REVENUE
ORDER BY SALES_MONTH;

#What percentage of total revenue comes from each product?
WITH PRODUCT_REVENUE AS (
SELECT P.PRODUCT_ID,P.PRODUCT_NAME,SUM(OI.QUANTITY * OI.UNIT_PRICE) AS REVENUE
FROM PRODUCTS P
JOIN ORDER_ITEMS OI
ON P.PRODUCT_ID = OI.PRODUCT_ID
GROUP BY P.PRODUCT_ID,P.PRODUCT_NAME)
SELECT PRODUCT_NAME,REVENUE,ROUND(REVENUE /SUM(REVENUE) OVER() * 100,2) AS PERCENT_OF_TOTAL_REVENUE
FROM PRODUCT_REVENUE
ORDER BY REVENUE DESC;