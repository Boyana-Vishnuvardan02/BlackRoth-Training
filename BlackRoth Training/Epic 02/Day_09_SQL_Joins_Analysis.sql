USE SALES_ANALYSIS_DB;

SELECT * FROM CUSTOMERS;
SELECT * FROM PRODUCTS;
SELECT * FROM ORDERS;
SELECT * FROM ORDER_ITEMS;

#Display customer names and their order IDs
SELECT C.CUSTOMER_NAME,O.ORDER_ID 
FROM CUSTOMERS C 
JOIN ORDERS O 
ON C.CUSTOMER_ID = O.CUSTOMER_ID;

#Display customer name, city and order date
SELECT C.CUSTOMER_NAME,C.CITY,O.ORDER_DATE
FROM CUSTOMERS C 
JOIN ORDERS O 
ON C.CUSTOMER_ID = O.CUSTOMER_ID;

#Display order ID and product ID, Category
SELECT OI.ORDER_ID,OI.PRODUCT_ID,P.CATEGORY 
FROM ORDER_ITEMS OI
JOIN PRODUCTS P 
ON OI.PRODUCT_ID = P.PRODUCT_ID;

#Display product name and quantity sold
SELECT P.PRODUCT_NAME,SUM(OI.QUANTITY) AS QUANTITY_SOLD FROM PRODUCTS P 
JOIN ORDER_ITEMS OI 
ON P.PRODUCT_ID = OI.PRODUCT_ID
GROUP BY PRODUCT_NAME;

#Display customer name, order ID and order status
SELECT C.CUSTOMER_NAME,O.ORDER_ID,O.ORDER_STATUS
FROM CUSTOMERS C 
JOIN ORDERS O 
ON C.CUSTOMER_ID = O.CUSTOMER_ID;

#Display all customers and their orders
SELECT C.CUSTOMER_NAME,C.CUSTOMER_ID,O.ORDER_ID 
FROM CUSTOMERS C
LEFT JOIN ORDERS O 
ON C.CUSTOMER_ID = O.CUSTOMER_ID;

#Find customers who have never placed an order
SELECT C.CUSTOMER_NAME,C.CUSTOMER_ID 
FROM CUSTOMERS C 
LEFT JOIN ORDERS O 
ON C.CUSTOMER_ID = O.CUSTOMER_ID
WHERE O.ORDER_ID IS NULL;

# Count orders placed by each customer
SELECT C.CUSTOMER_NAME,COUNT(O.ORDER_ID) AS ORDERS_PLACED 
FROM CUSTOMERS C 
LEFT JOIN ORDERS O 
ON C.CUSTOMER_ID = O.CUSTOMER_ID
GROUP BY C.CUSTOMER_NAME;

#Display all orders with customer information
SELECT C.CUSTOMER_NAME,C.CUSTOMER_ID,O.ORDER_DATE
FROM CUSTOMERS C 
RIGHT JOIN ORDERS O 
ON C.CUSTOMER_ID = O.CUSTOMER_ID;

#Find customers who placed more than 3 orders
SELECT C.CUSTOMER_NAME,COUNT(O.ORDER_ID) AS ORDERS_PLACED 
FROM CUSTOMERS C 
LEFT JOIN ORDERS O 
ON C.CUSTOMER_ID = O.CUSTOMER_ID
GROUP BY C.CUSTOMER_NAME
HAVING COUNT(O.ORDER_ID) > 3;

#Display customer name, order ID, product name, and quantity
SELECT C.CUSTOMER_NAME,O.ORDER_ID,P.PRODUCT_NAME,OI.QUANTITY
FROM CUSTOMERS C
INNER JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID
INNER JOIN ORDER_ITEMS OI
ON O.ORDER_ID = OI.ORDER_ID
INNER JOIN PRODUCTS P
ON OI.PRODUCT_ID = P.PRODUCT_ID;
    
#Display complete order details including customer, order, product, quantity, and price.
SELECT O.ORDER_ID,O.ORDER_DATE,C.CUSTOMER_NAME,P.PRODUCT_NAME,OI.QUANTITY,OI.UNIT_PRICE
FROM ORDERS O
INNER JOIN CUSTOMERS C
ON O.CUSTOMER_ID = C.CUSTOMER_ID
INNER JOIN ORDER_ITEMS OI
ON O.ORDER_ID = OI.ORDER_ID
INNER JOIN PRODUCTS P
ON OI.PRODUCT_ID = P.PRODUCT_ID;
    
#Calculate revenue for each order item
SELECT O.ORDER_ID,P.PRODUCT_NAME,OI.QUANTITY,OI.UNIT_PRICE,OI.QUANTITY * OI.UNIT_PRICE AS REVENUE
FROM ORDERS O
INNER JOIN ORDER_ITEMS OI
ON O.ORDER_ID = OI.ORDER_ID
INNER JOIN PRODUCTS P
ON OI.PRODUCT_ID = P.PRODUCT_ID;
    
#Calculate total revenue generated by each customer.
SELECT C.CUSTOMER_ID,C.CUSTOMER_NAME,SUM(OI.QUANTITY * OI.UNIT_PRICE) AS TOTAL_REVENUE
FROM CUSTOMERS C
INNER JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID
INNER JOIN ORDER_ITEMS OI
ON O.ORDER_ID = OI.ORDER_ID
GROUP BY C.CUSTOMER_ID,C.CUSTOMER_NAME
ORDER BY TOTAL_REVENUE DESC;

#Find the state that generates the highest revenue
SELECT C.STATE,SUM(OI.QUANTITY * OI.UNIT_PRICE) AS TOTAL_REVENUE
FROM CUSTOMERS C
INNER JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID
INNER JOIN ORDER_ITEMS OI
ON O.ORDER_ID = OI.ORDER_ID
GROUP BY C.STATE
ORDER BY TOTAL_REVENUE DESC
LIMIT 1;

#Calculate the number of customers and total revenue for each region.
SELECT C.REGION,COUNT(DISTINCT C.CUSTOMER_ID) AS TOTAL_CUSTOMERS,SUM(OI.QUANTITY * OI.UNIT_PRICE) AS TOTAL_REVENUE
FROM CUSTOMERS C
INNER JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID
INNER JOIN ORDER_ITEMS OI
ON O.ORDER_ID = OI.ORDER_ID
GROUP BY C.REGION
ORDER BY TOTAL_REVENUE DESC;

#Count the number of unique orders placed by each customer.
SELECT C.CUSTOMER_ID,C.CUSTOMER_NAME,COUNT(DISTINCT O.ORDER_ID) AS TOTAL_ORDERS
FROM CUSTOMERS C
LEFT JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID
GROUP BY C.CUSTOMER_ID,C.CUSTOMER_NAME;
    
#Display each category and the total quantity of products sold in that category.
SELECT P.CATEGORY,SUM(OI.QUANTITY) AS TOTAL_QUANTITY_SOLD
FROM PRODUCTS P
INNER JOIN ORDER_ITEMS OI
ON P.PRODUCT_ID = OI.PRODUCT_ID
GROUP BY P.CATEGORY
ORDER BY TOTAL_QUANTITY_SOLD DESC;

#Create a complete sales analysis using customers, orders, order items, and products.
SELECT C.CUSTOMER_ID,C.CUSTOMER_NAME,C.STATE,O.ORDER_ID,O.ORDER_DATE,P.PRODUCT_NAME,P.CATEGORY,OI.QUANTITY,OI.UNIT_PRICE,OI.QUANTITY * OI.UNIT_PRICE AS REVENUE
FROM CUSTOMERS C
INNER JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID
INNER JOIN ORDER_ITEMS OI
ON O.ORDER_ID = OI.ORDER_ID
INNER JOIN PRODUCTS P
ON OI.PRODUCT_ID = P.PRODUCT_ID
ORDER BY O.ORDER_DATE;

#Create a customer-wise sales analysis showing total orders, total items, and total revenue.
SELECT C.CUSTOMER_ID,C.CUSTOMER_NAME,C.STATE,COUNT(DISTINCT O.ORDER_ID) AS TOTAL_ORDERS,COALESCE(SUM(OI.QUANTITY), 0) AS TOTAL_ITEMS,COALESCE(SUM(OI.QUANTITY * OI.UNIT_PRICE), 0) AS TOTAL_REVENUE
FROM CUSTOMERS C
LEFT JOIN ORDERS O
ON C.CUSTOMER_ID = O.CUSTOMER_ID
LEFT JOIN ORDER_ITEMS OI
ON O.ORDER_ID = OI.ORDER_ID
GROUP BY C.CUSTOMER_ID,C.CUSTOMER_NAME,C.STATE
ORDER BY TOTAL_REVENUE DESC;
